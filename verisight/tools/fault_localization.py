"""
Spectrum-Based Fault Localization (SBFL) & Hardware APR Engine.

Inspired by:
1. CirFix: Automatically Repairing Defects in Hardware Design Code (ASPLOS '22)
   https://github.com/hammad-a/verilog_repair
2. Spectrum-Based Fault Localization (SBFL) using Tarantula and Ochiai metrics
   adapted for Verilog/SystemVerilog blocks, assignments, and signal paths.
"""

import math
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

from verisight.schemas.log_schema import LogKnowledge
from verisight.schemas.rtl_schema import RTLKnowledge
from verisight.utils.logger import get_logger

logger = get_logger("fault_localization")


class SuspectLocation(BaseModel):
    """An RTL statement or block ranked by suspiciousness score."""
    file_path: str = ""
    module_name: str = ""
    line_number: int = 0
    signal_name: str = ""
    block_type: str = ""
    suspiciousness: float = 0.0  # 0.0 to 1.0 (Ochiai score)
    failed_tests: int = 0
    passed_tests: int = 0
    repair_hint: str = ""


class FaultLocalizationReport(BaseModel):
    """Report generated by the SBFL engine ranking candidate RTL defects."""
    tool_status: str = "ok"
    total_passed_scenarios: int = 0
    total_failed_scenarios: int = 0
    ranked_suspects: List[SuspectLocation] = Field(default_factory=list)
    top_suspect: Optional[SuspectLocation] = None
    metric_used: str = "Ochiai"


def compute_ochiai(failed_e: int, passed_e: int, total_failed: int) -> float:
    """Computes standard Ochiai coefficient for fault suspiciousness."""
    if total_failed == 0 or (failed_e + passed_e) == 0:
        return 0.0
    denominator = math.sqrt(total_failed * (failed_e + passed_e))
    if denominator == 0.0:
        return 0.0
    return round(failed_e / denominator, 4)


def compute_tarantula(failed_e: int, passed_e: int, total_failed: int, total_passed: int) -> float:
    """Computes standard Tarantula metric."""
    if total_failed == 0:
        return 0.0
    fail_ratio = failed_e / total_failed
    pass_ratio = (passed_e / total_passed) if total_passed > 0 else 0.0
    denom = fail_ratio + pass_ratio
    return round(fail_ratio / denom, 4) if denom > 0 else 0.0


def localize_faults(
    log_data: Optional[LogKnowledge],
    rtl_data: Optional[RTLKnowledge],
) -> FaultLocalizationReport:
    """
    Ranks RTL statements and signals by defect suspiciousness using simulation execution logs.

    Args:
        log_data: Extracted simulation log knowledge (containing scenarios, errors, mismatches).
        rtl_data: Extracted RTL knowledge (modules, ports, always blocks).

    Returns:
        FaultLocalizationReport with sorted suspect RTL locations.
    """
    if not log_data:
        return FaultLocalizationReport(tool_status="no_log_data")

    # Detect test scenarios from log entries
    passed_scenarios = 0
    failed_scenarios = 0
    error_signals: Dict[str, int] = {}
    pass_signals: Dict[str, int] = {}

    for entry in getattr(log_data, "entries", []):
        msg = entry.message or ""
        msg_upper = msg.upper()
        if "PASS" in msg_upper or "MATCH" in msg_upper and "MISMATCH" not in msg_upper:
            passed_scenarios += 1
            # Track signals associated with pass
            for word in msg.split():
                if "ADDR=" in word or "DATA=" in word or "REG_" in word:
                    clean = word.split("=")[-1].strip(",")
                    pass_signals[clean] = pass_signals.get(clean, 0) + 1
        elif "ERROR" in msg_upper or "MISMATCH" in msg_upper or "FAIL" in msg_upper:
            failed_scenarios += 1
            # Track signals associated with fail
            for word in msg.split():
                if "ADDR=" in word or "DATA=" in word or "REG_" in word or "EXPECTED=" in word:
                    clean = word.split("=")[-1].strip(",")
                    error_signals[clean] = error_signals.get(clean, 0) + 1

    total_failed = max(failed_scenarios, len(getattr(log_data, "errors", [])))
    total_passed = max(passed_scenarios, 1)

    # Rank RTL always blocks and signals
    suspects: List[SuspectLocation] = []

    if rtl_data and rtl_data.modules:
        for mod in rtl_data.modules:
            for block in getattr(mod, "always_blocks", []):
                block_sigs = (
                    getattr(block, "signals_written", [])
                    or getattr(block, "signals_read", [])
                    or getattr(block, "assigned_signals", [])
                    or getattr(block, "signals", [])
                )
                line_no = getattr(block, "line_number", 0)
                file_p = getattr(mod, "file_path", "")

                for sig in block_sigs:
                    f_count = 0
                    p_count = 0
                    for err_k, err_cnt in error_signals.items():
                        if sig.lower() in err_k.lower() or err_k.lower() in sig.lower():
                            f_count += err_cnt
                    for p_k, p_cnt in pass_signals.items():
                        if sig.lower() in p_k.lower() or p_k.lower() in sig.lower():
                            p_count += p_cnt

                    # Baseline score from error presence if specific counts unavailable
                    if f_count == 0 and total_failed > 0:
                        # Check if block mentions any failing signal or subtoken (e.g. data0 in reg_data0)
                        sig_parts = [p for p in sig.lower().split("_") if len(p) > 2]
                        for err in getattr(log_data, "errors", []):
                            err_msg = (err.message or "").lower()
                            if sig.lower() in err_msg or any(p in err_msg for p in sig_parts):
                                f_count += 1

                    if f_count > 0:
                        score = compute_ochiai(f_count, p_count, total_failed)
                        repair_hint = f"Inspect assignments to '{sig}' in {mod.name} at line {line_no}."
                        suspects.append(SuspectLocation(
                            file_path=file_p,
                            module_name=mod.name,
                            line_number=line_no,
                            signal_name=sig,
                            block_type=getattr(block, "block_type", "always_ff"),
                            suspiciousness=score,
                            failed_tests=f_count,
                            passed_tests=p_count,
                            repair_hint=repair_hint,
                        ))

    # Sort descending by suspiciousness
    suspects.sort(key=lambda s: s.suspiciousness, reverse=True)
    top = suspects[0] if suspects else None

    return FaultLocalizationReport(
        tool_status="ok",
        total_passed_scenarios=total_passed,
        total_failed_scenarios=total_failed,
        ranked_suspects=suspects[:15],
        top_suspect=top,
        metric_used="Ochiai (CirFix methodology)",
    )
